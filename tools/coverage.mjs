#!/usr/bin/env node
// Which pixelfx effects the game uses, and where. Writes src/data/fxuse.js (shown in the in-game codex) and fails
// if any effect in the library is left out.
//
//   node tools/coverage.mjs

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { FX } from "../src/pfx.js";
import { SKILLS } from "../src/data/skills.js";
import { ENEMIES } from "../src/data/enemies.js";
import { WEAPONS } from "../src/data/weapons.js";
import { STATUS } from "../src/game/status.js";

const ROOT = new URL("..", import.meta.url).pathname;
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (p.endsWith(".js") && !p.endsWith("fxuse.js")) files.push(p);
  }
};
walk(join(ROOT, "src"));
const ids = Object.keys(FX), where = Object.fromEntries(ids.map((id) => [id, new Set()]));
const LABEL = {
  "game/combat.js": "combat", "game/ents.js": "world", "world/populate.js": "world", "game/director.js": "weather & events", "game/bosses.js": "bosses",
  "game/game.js": "the hero's life", "game/hero.js": "the hero", "ui/ui.js": "interface", "game/quests.js": "quests", "game/skills.js": "skills", "game/rpg.js": "items",
  "data/items.js": "items", "game/enemies.js": "enemies", "game/npcs.js": "people",
};
for (const f of files) {
  const src = readFileSync(f, "utf8"), rel = relative(join(ROOT, "src"), f);
  for (const m of src.matchAll(/["'`]([a-z]+\/[a-z0-9-]+)["'`]/g)) if (where[m[1]] && LABEL[rel]) where[m[1]].add(LABEL[rel]);
  // weather is named without its category in the data
  if (rel === "world/biomes.js" || rel === "game/director.js") for (const m of src.matchAll(/"([a-z-]+)"/g)) if (FX["weather/" + m[1]]) where["weather/" + m[1]].add("weather");
}
for (const [k, s] of Object.entries(SKILLS)) where[s.fx]?.add("skill: " + s.name);
for (const [k, e] of Object.entries(ENEMIES)) {
  if (e.fx) where[e.fx]?.add("foe: " + e.name);
  if (e.death) where[e.death]?.add("death of " + e.name);
  for (const a of e.attacks ?? []) where[a]?.add("foe: " + e.name);
}
for (const w of Object.values(WEAPONS)) for (const c of w.combo ?? []) where[c]?.add("weapon: " + w.name);
for (const [k, s] of Object.entries(STATUS)) where[s.fx]?.add("status: " + s.label);
// the transitions are named in the UI table
for (const id of ids.filter((i) => i.startsWith("transitions/"))) if (readFileSync(join(ROOT, "src/ui/ui.js"), "utf8").includes(id) || files.some((f) => readFileSync(f, "utf8").includes(id))) where[id].add("transition");
const missing = ids.filter((id) => !where[id].size);
const out = Object.fromEntries(ids.map((id) => [id, [...where[id]].slice(0, 3).join(", ").toUpperCase()]));
writeFileSync(join(ROOT, "src/data/fxuse.js"), "// Generated by tools/coverage.mjs: where each pixelfx effect appears in the game.\nexport const USES = " + JSON.stringify(out, null, 1) + ";\n");
console.log(`${ids.length - missing.length}/${ids.length} effects used`);
if (missing.length) {
  console.log("missing:\n  " + missing.join("\n  "));
  process.exit(1);
}
